"""Builds js/audio-data.js from the real recordings in tools/sources/ (downloaded from
Wikimedia Commons, see the Credits on the How-to tab). Each sound is made mono,
crossfaded into a seamless loop, AAC-encoded and embedded as base64 so the site
works by double-clicking index.html.  Run: python3 tools/make_audio.py  (macOS)"""
import array, base64, math, os, subprocess, tempfile, wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "sources")
TMP = tempfile.mkdtemp()

SOUNDS = {
    # name: (source files joined in order, sample rate, AAC bitrate)
    "TALKING": (["Group_discussion_3.ogg.mp3", "Group_discussion_1.ogg.mp3"], 22050, 48000),
    "CONSTRUCTION": (["Baustelle_am_Moedlingbach.wav"], 32000, 64000),
}
JOIN_FADE = 1.0   # seconds of crossfade between clips
LOOP_FADE = 1.5   # seconds of crossfade at the loop point
TARGET_RMS_DBFS = -24


def read_mono(path, rate):
    out = os.path.join(TMP, os.path.basename(path) + ".wav")
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{rate}", "-c", "1", path, out], check=True)
    with wave.open(out) as w:
        samples = array.array("h", w.readframes(w.getnframes()))
    return [s / 32768 for s in samples]


def trim_silence(x, rate, threshold=0.01):
    block = rate // 20
    start, end = 0, len(x)
    while start + block < end and max(abs(v) for v in x[start:start + block]) < threshold:
        start += block
    while end - block > start and max(abs(v) for v in x[end - block:end]) < threshold:
        end -= block
    return x[start:end]


def crossfade_join(a, b, n):
    n = min(n, len(a), len(b))
    mixed = [a[len(a) - n + i] * math.cos(i / n * math.pi / 2) + b[i] * math.sin(i / n * math.pi / 2) for i in range(n)]
    return a[:len(a) - n] + mixed + b[n:]


def make_loop(x, n):
    # blend the tail into the head so the end flows straight back into the start
    body = x[:len(x) - n]
    for i in range(n):
        w = math.sin(i / n * math.pi / 2)
        body[i] = body[i] * w + x[len(x) - n + i] * math.cos(i / n * math.pi / 2)
    return body


def report(name, x, rate):
    rms = math.sqrt(sum(v * v for v in x) / len(x))
    peak = max(abs(v) for v in x)
    secs = [math.sqrt(sum(v * v for v in x[i:i + rate]) / rate) for i in range(0, len(x) - rate, rate)]
    quiet = sum(1 for s in secs if s < rms * 0.25) / len(secs)
    print(f"{name}: {len(x)/rate:.1f}s  rms {20*math.log10(rms):.1f} dBFS  peak {20*math.log10(peak):.1f} dBFS  "
          f"crest {20*math.log10(peak/rms):.1f} dB  near-silent seconds {quiet*100:.0f}%")


lines = ["// AUTO-GENERATED by tools/make_audio.py - real background recordings (AAC, base64).\n"]
for name, (files, rate, bitrate) in SOUNDS.items():
    clip = []
    for f in files:
        part = trim_silence(read_mono(os.path.join(SRC, f), rate), rate)
        clip = crossfade_join(clip, part, int(JOIN_FADE * rate)) if clip else part
    clip = make_loop(clip, int(LOOP_FADE * rate))
    # same loudness for both before encoding (the site fine-tunes it again when playing)
    gain = 10 ** (TARGET_RMS_DBFS / 20) / math.sqrt(sum(v * v for v in clip) / len(clip))
    gain = min(gain, 0.97 / max(abs(v) for v in clip))
    clip = [v * gain for v in clip]
    report(name, clip, rate)
    wav = os.path.join(TMP, name + ".wav")
    with wave.open(wav, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
        w.writeframes(array.array("h", (max(-32768, min(32767, int(v * 32767))) for v in clip)).tobytes())
    m4a = os.path.join(TMP, name + ".m4a")
    subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", str(bitrate), wav, m4a], check=True)
    with open(m4a, "rb") as f:
        b64 = base64.b64encode(f.read()).decode()
    lines.append(f'const {name}_AUDIO_BASE64 = "{b64}";\n')
    print(f"   -> {len(b64)//1024} KB base64")

with open(os.path.join(ROOT, "js", "audio-data.js"), "w") as f:
    f.writelines(lines)
